"""
Gerber RS-274X and Excellon writers for the package board, driven from
the copper description the Altium export leaves in a combination's
folder (`copper.txt`, see `fab_drawing.parse_package_copper`) and the
combination's equation values.

Why this exists next to Altium's own output jobs: the copper, outline
and drill data are fully described by that file, so a fab set can be
written in a fraction of a second, with no Altium session and nothing
that can park on a dialog -- and written the same way every time. It is
the fallback that is always available; Altium's own Gerber/ODB++/IPC-2581
outputs, when they have been generated, are listed beside it.

What it writes (all coordinates millimetres, 4.6 format, board centre at
the origin as in Altium):

    <name>_F_Cu.gbr         top copper: tracks, pads, regions, via lands
    <name>_B_Cu.gbr         bottom copper: regions and via lands
    <name>_Edge_Cuts.gbr    board outline (and the die opening if it goes through)
    <name>_PTH.drl          Excellon, plated holes (vias)
    <name>_NPTH.drl         Excellon, non-plated holes (screw clearance)
"""
from __future__ import annotations

from typing import Dict, List, Tuple

from . import cavity, pcb_outline, screws

_SCALE = 1_000_000          # 4.6 format, millimetres


def _c(value: float) -> str:
    return str(int(round(value * _SCALE)))


def _header(name: str, function: str, polarity: str = "Positive") -> List[str]:
    return [
        "G04 Generated by microwave_package*",
        f"%TF.GenerationSoftware,microwave_package,gerber*%",
        f"%TF.FileFunction,{function}*%",
        f"%TF.FilePolarity,{polarity}*%",
        "%FSLAX46Y46*%",
        "%MOMM*%",
        "G01*",
        "G75*",
    ]


class _Apertures:
    def __init__(self) -> None:
        self._by_key: Dict[tuple, int] = {}
        self.defs: List[str] = []

    def get(self, shape: str, *size: float) -> int:
        key = (shape,) + tuple(round(s, 6) for s in size)
        if key not in self._by_key:
            number = 10 + len(self._by_key)
            self._by_key[key] = number
            dims = "X".join(f"{s:.6f}".rstrip("0").rstrip(".") for s in size)
            self.defs.append(f"%ADD{number}{shape},{dims}*%")
        return self._by_key[key]


def _region(points: List[Tuple[float, float]]) -> List[str]:
    if len(points) < 3:
        return []
    out = ["G36*"]
    x, y = points[0]
    out.append(f"X{_c(x)}Y{_c(y)}D02*")
    for x, y in points[1:] + [points[0]]:
        out.append(f"X{_c(x)}Y{_c(y)}D01*")
    out.append("G37*")
    return out


def copper_layer(copper: Dict[str, list], side: str, name: str) -> str:
    """One copper layer ("top" or "bottom"). Via lands appear on both."""
    function = "Copper,L1,Top" if side == "top" else "Copper,L2,Bot"
    ap = _Apertures()
    body: List[str] = []

    for layer, coords in copper.get("region", []):
        if layer != side:
            continue
        points = list(zip(coords[0::2], coords[1::2]))
        body += _region(points)

    for layer, x1, y1, x2, y2, width in copper.get("track", []):
        if layer != side:
            continue
        body.append(f"D{ap.get('C', width)}*")
        body.append(f"X{_c(x1)}Y{_c(y1)}D02*")
        body.append(f"X{_c(x2)}Y{_c(y2)}D01*")

    for layer, x, y, xs, ys, rot in copper.get("pad", []):
        if layer != side:
            continue
        if int(round(rot)) % 180 == 90:
            xs, ys = ys, xs
        body.append(f"D{ap.get('R', xs, ys)}*")
        body.append(f"X{_c(x)}Y{_c(y)}D03*")

    for x, y, diameter, _hole in copper.get("via", []):
        body.append(f"D{ap.get('C', diameter)}*")
        body.append(f"X{_c(x)}Y{_c(y)}D03*")

    lines = _header(name, function) + ap.defs + ["%LPD*%"] + body + ["M02*"]
    return "\n".join(lines) + "\n"


def _rounded_profile(hl: float, hs: float, radius: float) -> List[str]:
    """A closed profile with the four corners as G03 arcs (counter-clockwise,
    I/J from each arc's start to its centre), joined by straight edges."""
    arcs = pcb_outline.corner_arcs(hl, hs, radius)
    start = arcs[0][1]
    out = [f"X{_c(start[0])}Y{_c(start[1])}D02*"]
    for k, (centre, arc_start, arc_end) in enumerate(arcs):
        out.append("G03*")
        out.append(f"X{_c(arc_end[0])}Y{_c(arc_end[1])}"
                   f"I{_c(centre[0] - arc_start[0])}J{_c(centre[1] - arc_start[1])}D01*")
        nxt = arcs[(k + 1) % len(arcs)][1]
        out.append("G01*")
        out.append(f"X{_c(nxt[0])}Y{_c(nxt[1])}D01*")
    return out


def outline_layer(values: Dict[str, float], name: str) -> str:
    """The board outline, as a closed 0.1 mm profile -- its corners as arcs
    when the PCB is rounded -- plus the die's opening where it goes through
    the board."""
    length = values.get("pcb_length", 50.0)
    side = values.get("pcb_side", 25.0)
    radius = pcb_outline.corner_radius_of(values)
    ap = _Apertures()
    ap.get("C", 0.1)
    body = ["D10*"]

    def box(hl: float, hs: float) -> List[str]:
        pts = [(-hl, -hs), (hl, -hs), (hl, hs), (-hl, hs), (-hl, -hs)]
        out = [f"X{_c(pts[0][0])}Y{_c(pts[0][1])}D02*"]
        out += [f"X{_c(x)}Y{_c(y)}D01*" for x, y in pts[1:]]
        return out

    if radius > 0.0:
        body += _rounded_profile(length / 2.0, side / 2.0, radius)
    else:
        body += box(length / 2.0, side / 2.0)
    cav = cavity.plan(values)
    if not cav.is_empty and cav.through:
        body += box(cav.half_length, cav.half_side)
    lines = _header(name, "Profile,NP") + ap.defs + ["%LPD*%"] + body + ["M02*"]
    return "\n".join(lines) + "\n"


def _excellon(holes: List[Tuple[float, float, float]], plated: bool) -> str:
    tools: Dict[float, int] = {}
    for _x, _y, d in holes:
        tools.setdefault(round(d, 4), len(tools) + 1)
    lines = [
        "M48",
        "; Generated by microwave_package",
        f"; #@! TF.FileFunction,{'Plated' if plated else 'NonPlated'},1,2,{'PTH' if plated else 'NPTH'}",
        "FMAT,2",
        "METRIC,TZ",
    ]
    for diameter, number in tools.items():
        lines.append(f"T{number}C{diameter:.3f}")
    lines += ["%", "G90", "G05"]
    for diameter, number in tools.items():
        lines.append(f"T{number}")
        for x, y, d in holes:
            if round(d, 4) == diameter:
                lines.append(f"X{x:.4f}Y{y:.4f}")
    lines.append("M30")
    return "\n".join(lines) + "\n"


def drill_files(values: Dict[str, float], copper: Dict[str, list]) -> Dict[str, str]:
    """{'PTH': text, 'NPTH': text} -- the NPTH file only when there is
    something to put in it."""
    plated = [(x, y, hole) for x, y, _dia, hole in copper.get("via", [])]
    out: Dict[str, str] = {"PTH": _excellon(plated, True)}
    plan = screws.plan(values)
    if plan is not None:
        out["NPTH"] = _excellon(
            [(u, v, plan.clearance_diameter) for u, v in plan.positions], False
        )
    return out


def fab_set(values: Dict[str, float], copper: Dict[str, list], name: str) -> Dict[str, str]:
    """Every file of the set, keyed by file name."""
    files = {
        f"{name}_F_Cu.gbr": copper_layer(copper, "top", name),
        f"{name}_B_Cu.gbr": copper_layer(copper, "bottom", name),
        f"{name}_Edge_Cuts.gbr": outline_layer(values, name),
    }
    for kind, text in drill_files(values, copper).items():
        files[f"{name}_{kind}.drl"] = text
    return files
